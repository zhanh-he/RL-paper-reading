"""Constructed BCR-v1 attack probes, never presented as model generations."""
import argparse
import json
from pathlib import Path
import sys

import numpy as np
import soundfile as sf

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "rl/grpo"))
import train_lada_band as base
from combine import combine


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reward-root", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, args.reward_root)
    from mir.reward_function.beat_v5 import BeatV5Config, BeatV5Scorer
    from mir.reward_function.coverage import accompaniment_coverage
    BeatV5Scorer._compatibility_shims()
    scorer = BeatV5Scorer(BeatV5Config(segment_seconds=12, madmom_workers=1), backend="madmom")
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    sr = 48000
    time = np.arange(sr * 12) / sr
    envelope = np.minimum(1, ((time % 0.5) / 0.04)) * np.exp(-(time % 0.5) / 0.16)
    vocal = 0.1 * envelope * (np.sin(2 * np.pi * 220 * time) + 0.3 * np.sin(2 * np.pi * 440 * time))
    vocal_path = out / "constructed_reference.wav"
    sf.write(vocal_path, vocal, sr, subtype="PCM_24")
    rng = np.random.default_rng(13)
    chord = sum(np.sin(2 * np.pi * f * time) for f in (130.81, 164.81, 196.00)) / 3
    signals = {"silence": np.zeros_like(time), "constant_drone": 0.08 * np.sin(2 * np.pi * 220 * time),
               "white_noise": rng.normal(0, 0.08, len(time)), "envelope_chord": 0.1 * chord * envelope,
               "detuned_layers": 0.1 * envelope * sum(np.sin(2 * np.pi * f * time) for f in (141, 177, 209)) / 3,
               "clipped_chord": np.clip(4 * chord, -1, 1)}
    receipts = []
    for name, audio in signals.items():
        path = out / f"constructed_{name}.wav"
        sf.write(path, audio, sr, subtype="FLOAT")
        beat = scorer.score_paths(vocal_path, path)
        coverage = accompaniment_coverage(audio, sr)
        metrics = base.score_audio(audio, base.frame_rms(vocal, sr), sr, "combined")
        richness = base.richness_v0_score(audio, base.frame_rms(vocal, sr), sr, 0)
        rich_raw = float(np.clip(richness["reward"] + richness["loudness_guard_penalty"], 0, 1))
        delta_db = 20 * np.log10(max(float(np.sqrt(np.mean(audio ** 2))), 1e-8) / 0.05)
        combined = combine(beat.score, coverage, rich_raw, beat_scorable=not beat.abstain,
                           quality_penalty=metrics["quality_penalty"],
                           loudness_penalty=0.025 * max(0, abs(delta_db) - 6))
        receipts.append({"case": name, "provenance": "constructed function probe, not generated by LaDA",
                         "audio": str(path), **combined})
    (out / "audit.json").write_text(json.dumps(receipts, indent=2))
    print(json.dumps(receipts, indent=2), flush=True)


if __name__ == "__main__":
    main()
